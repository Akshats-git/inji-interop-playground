/** Per-run interop report (PS2 task 7): issuer, wallet, verifier, format, proof type, outcome, error detail. */
import {
  credentialStatusLabel,
  KNOWN_GAPS,
  knownGapOf,
  PARTY_LABEL,
  type EventSummary,
  type Run,
} from "@playground/core";

export function redactRun(run: Run): Run {
  return {
    ...run,
    spec: {
      ...run.spec,
      claims: Object.fromEntries(Object.keys(run.spec.claims).map((k) => [k, "‹redacted›"])),
      txCode: run.spec.txCode ? "‹redacted›" : undefined,
    },
  };
}

export function runReportMarkdown(run: Run, events: EventSummary[]): string {
  const r = run.result;
  const gap = knownGapOf(run);
  const verdict = r
    ? r.verdict === "PASS"
      ? "✅ PASS"
      : gap
        ? `⚠️ FAIL (known gap ${gap})`
        : "❌ FAIL"
    : "⏳ in progress";
  const issuerSoftware = run.labels.external?.issuer
    ? (run.labels.versions[run.labels.issuerName] ?? "external issuer")
    : `Inji Certify ${run.labels.versions["Inji Certify"]}`;
  const lines = [
    `# Interop run ${run.id}: ${verdict}`,
    "",
    `Generated by the Inji Interoperability Playground on ${new Date().toISOString()}.`,
    "",
    "| Field | Value |",
    "|---|---|",
    `| Issuer | ${run.labels.issuerName} (${issuerSoftware}) |`,
    `| Credential type | ${run.labels.typeName} |`,
    `| Wallet | ${run.labels.wallet} |`,
    `| Verifier | ${run.labels.verifier} |`,
    `| Format | ${run.labels.format}${run.labels.dataModel ? ` (VCDM ${run.labels.dataModel})` : ""} |`,
    `| Proof type | ${run.labels.proofType} |`,
    `| Query language | ${run.spec.mode === "direct-share" ? "n/a (direct share)" : run.spec.query === "dcql" ? "DCQL" : "Presentation Exchange"} |`,
    `| Mode | ${run.spec.mode} |`,
    `| Tamper preset | ${run.spec.tamper} |`,
    `| Expected | ${r?.expected ?? "n/a"} |`,
    `| Verifier outcome | ${r?.verifierOutcome ?? "n/a"} |`,
    `| Credential status | ${credentialStatusLabel(r?.credentialStatus) ?? r?.credentialStatus ?? "n/a"} |`,
    ...(gap ? [`| Known gap | ${gap}: ${KNOWN_GAPS[gap]} (docs/gaps.md) |`] : []),
    `| Error | ${r?.errorCode ? `\`${r.errorCode}\`${r.errorDetail ? `: ${r.errorDetail}` : ""}` : "n/a"} |`,
    "",
    "## What happened",
    "",
    r?.explanation ?? "The run has not finished.",
    "",
    "## Steps",
    "",
    ...run.steps.map((s) => `- **${s.name}**: ${s.status}${s.note ? `. ${s.note}` : ""}`),
    "",
  ];
  if (r?.checks.length)
    lines.push(
      "## Checks",
      "",
      ...r.checks.map((c) => `- ${c.ok ? "✅" : "❌"} ${c.name}${c.detail ? `: ${c.detail}` : ""}`),
      "",
    );
  lines.push(
    "## Protocol messages",
    "",
    "| # | Time | From → To | Message | HTTP | Labels |",
    "|---|---|---|---|---|---|",
    ...events.map(
      (e) =>
        `| ${e.seq} | ${e.at.slice(11, 23)} | ${PARTY_LABEL[e.from]} → ${PARTY_LABEL[e.to]} | ${e.title} | ${e.status} | ${e.labels.join(", ")} |`,
    ),
    "",
    "Versions: " +
      Object.entries(run.labels.versions)
        .map(([k, v]) => `${k} ${v}`)
        .join(" · "),
    "",
  );
  return lines.join("\n");
}
